export const translations: Record<Language, Record<TranslationKey, string>> = {
  nl: messagesNl,
  en: messagesEn
};

export function translate<K extends TranslationKey>(
  language: Language,
  key: K,
  ...args: TranslationArguments<K>
): string {
  let message = translations[language][key];
  const parameters = args[0] as Record<string, string | number> | undefined;
  if (!parameters) return message;

  for (const [name, value] of Object.entries(parameters)) {
    const formatted = typeof value === 'number' ? new Intl.NumberFormat(language).format(value) : value;
    message = message.replaceAll(`{${name}}`, formatted);
  }
  return message;
}

